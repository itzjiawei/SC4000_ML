def ci(b):
    return f"{b['diff']:+.4f} [{b['ci_low']:+.4f}, {b['ci_high']:+.4f}]"


def model_table():
    ref = pd.read_csv(OOF / "ref_lr_seed_only.csv")
    lines = ["| Group | Model | Tune 2012–16 | Report men | Report women | **Report combined** | vs seed-only LR [95% CI] |",
             "|---|---|---|---|---|---|---|"]
    for name, label, group in MODELS:
        o = pd.read_csv(OOF / f"{name}.csv")
        s = cv.summarise(o)
        vs = "–" if name in ("ref_lr_seed_only", "ref_coinflip") else ci(cv.paired_bootstrap(o, ref))
        lines.append(f"| {group} | {label} | {s['tune_combined']:.4f} | {s['report_men']:.4f} | "
                     f"{s['report_women']:.4f} | **{s['report_combined']:.4f}** | {vs} |")
    return "\n".join(lines)


def csv_table(path, cols, rename=None, fmt=None):
    t = pd.read_csv(path)[cols].rename(columns=rename or {})
    fmt = fmt or {}
    head = "| " + " | ".join(t.columns) + " |\n|" + "---|" * len(t.columns)
    body = []
    for _, r in t.iterrows():
        cells = []
        for c in t.columns:
            v = r[c]
            cells.append(fmt[c].format(v) if c in fmt and pd.notna(v) else ("–" if pd.isna(v) else str(v)))
        body.append("| " + " | ".join(cells) + " |")
    return head + "\n" + "\n".join(body)


def ablation_table():
    t = pd.read_csv(cv.OUT_DIR / "final_ablation.csv")
    lines = ["| Experiment | Report combined | Men | Women | Change vs full [95% CI] |", "|---|---|---|---|---|"]
    for _, r in t.iterrows():
        ch = "–" if pd.isna(r.get("change")) else f"{r.change:+.4f} [{r.ci_low:+.4f}, {r.ci_high:+.4f}]"
        lines.append(f"| {r.Experiment} | {r.report_combined:.4f} | {r.report_men:.4f} | {r.report_women:.4f} | {ch} |")
    return "\n".join(lines)


